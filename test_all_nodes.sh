send_node_data() {
    local node=$1
    local timestamp=$2
    local cycle=$3
    local subject=$4

    local macs="${CLASS_MACS[$node]}"
    local count="${CLASS_STUDENTS[$node]}"
    local class_name="${CLASS_NAMES[$node]}"

    # Convert comma-separated to JSON array
    local json_macs=$(echo "$macs" | sed 's/,/","/g' | sed 's/^/"/' | sed 's/$/"/')

    local response=$(curl -s -w "\n%{http_code}" -X POST "$API_URL" \
      -H "Content-Type: application/json" \
      -H "Authorization: Bearer $API_KEY" \
      -d "{
        \"gateway_id\": \"$GATEWAY_ID\",
        \"node_id\": $node,
        \"timestamp\": $timestamp,
        \"student_count\": $count,
        \"rssi\": -70,
        \"snr\": 9.0,
        \"cycle\": $cycle,
        \"mac_addresses\": [$json_macs]
      }")

    local http_code=$(echo "$response" | tail -n1)
    local body=$(echo "$response" | head -n-1)

    if [ "$http_code" == "200" ] || [ "$http_code" == "201" ]; then
        local processed=$(echo "$body" | jq -r '.data.processed // 0')
        local total=$(echo "$body" | jq -r '.data.total // 0')
        local skipped=$(echo "$body" | jq -r '.data.skipped // 0')
        log_success "Node $node ($class_name) | Subject: $subject | Students: $count | Processed: $processed/$total | Skipped: $skipped"
    else
        log_error "Node $node ($class_name) | HTTP $http_code | Response: $body"
    fi
}

send_schedule_parallel() {
    local timestamp=$1
    local cycle=$2
    local subject=$3
    local time_label=$4

    log_info "================================================"
    log_info "Schedule $cycle: $subject ($time_label)"
    log_info "================================================"

    # Send requests in batches
    for node in {1..30}; do
        send_node_data "$node" "$timestamp" "$cycle" "$subject" &

        # Control parallel jobs
        if (( node % PARALLEL_JOBS == 0 )); then
            wait
        fi
    done

    # Wait for remaining jobs
    wait

    log_success "Schedule $cycle completed ✓"
    echo ""
}

check_prerequisites() {
    log_info "Checking prerequisites..."

    # Check if jq is installed
    if ! command -v jq &> /dev/null; then
        log_error "jq is not installed. Please install it first:"
        echo "  Ubuntu/Debian: sudo apt-get install jq"
        echo "  MacOS: brew install jq"
        exit 1
    fi

    # Check if API is accessible
    if ! curl -s -f -o /dev/null "$API_URL" 2>/dev/null; then
        log_warning "API endpoint might not be accessible: $API_URL"
        read -p "Continue anyway? (y/n): " -n 1 -r
        echo
        if [[ ! $REPLY =~ ^[Yy]$ ]]; then
            exit 1
        fi
    fi

    log_success "Prerequisites check passed"
}

